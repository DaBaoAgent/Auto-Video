// ---------------------------------------------------------------- 行宽归一化
// 手写表时右边缘偶尔漏 1~2 格（都是纯透明列），会让 buildSpr 的 w 变成"最宽那一行"，
// 几何不确定、并刷一堆 [spr] 行宽告警。这里统一补 '.' 到本表最大宽度：
// w 不变（仍是设计宽度），左对齐，右边缘透明，视觉与原来完全一致。
for (const t of [EXC_BODY, EXC_TRACK, EXC_BOOM, EXC_ARM, BUCKET, BUCKET_DIRT,
  STONE_TILE, RING_HANDLE, ROPE_BOSS, SARCO_END, SARCO_LID_END,
  PERSON_F0, PERSON_F1, PERSON_F2, PERSON_F3, PERSON_F4, PERSON_F5, ARMOR]) {
  const w = Math.max(...t.map(r => r.replace(/\s+/g, '').length));
  for (let i = 0; i < t.length; i++) {
    const n = t[i].replace(/\s+/g, '').length;
    if (n < w) t[i] += '.'.repeat(w - n);
  }
}

