def only_cjk(s):
    return re.sub(r"[^\u4e00-\u9fff]", "", s)


def py(s):
    from pypinyin import lazy_pinyin, Style
    return lazy_pinyin(s, style=Style.NORMAL)


def split_captions(text, max_len=16):
    """切成 <=16 字的字幕块：先按句，再在逗号/顿号处二次切。"""
    sents = re.split(r"(?<=[。？！；：])", text)
    sents = [s for s in (x.strip() for x in sents) if s]
    chunks = []
    for s in sents:
        if len(only_cjk(s)) <= max_len:
            chunks.append(s)
            continue
        parts = re.split(r"(?<=[，,、])", s)
        buf = ""
        for p in parts:
            if buf and len(only_cjk(buf + p)) > max_len:
                chunks.append(buf)
                buf = p
            else:
                buf += p
        if buf:
            chunks.append(buf)
    return chunks


def dp_align(src_pys, tgt_pys):
    """返回 {src_idx: tgt_idx}"""
    n, m = len(src_pys), len(tgt_pys)
    dp = [[0] * (m + 1) for _ in range(n + 1)]
    for i in range(n + 1):
        dp[i][0] = i
    for j in range(m + 1):
        dp[0][j] = j
    for i in range(1, n + 1):
        row, prev = dp[i], dp[i - 1]
        for j in range(1, m + 1):
            c = 0 if src_pys[i - 1] == tgt_pys[j - 1] else 1
            row[j] = min(prev[j] + 1, row[j - 1] + 1, prev[j - 1] + c)
    align = {}
    i, j = n, m
    while i > 0 and j > 0:
        c = 0 if src_pys[i - 1] == tgt_pys[j - 1] else 1
        if dp[i][j] == dp[i - 1][j - 1] + c:
            align[i - 1] = j - 1; i -= 1; j -= 1
        elif dp[i][j] == dp[i - 1][j] + 1:
            align[i - 1] = j; i -= 1
        else:
            j -= 1
    while i > 0:
        align[i - 1] = j; i -= 1
    return align


def char_time(align, units, k, which="start"):
    a = align.get(k)
    if a is None or a >= len(units):
        a = len(units) - 1
    if a < 0:
        return 0.0
    return units[a][1] if which == "start" else units[a][2]


def process_part(pid, scenes):
    d = os.path.join(OUT_DIR, pid)
    os.makedirs(d, exist_ok=True)
    mp3 = os.path.join(d, "narration.mp3")
    manifest_path = os.path.join(d, "manifest.json")
    if os.path.exists(manifest_path):
        print(f"[{pid}] manifest 已存在，跳过", flush=True)
        return

    txt_path = os.path.join(PARTS_DIR, pid + ".txt")
    os.makedirs(PARTS_DIR, exist_ok=True)
    with open(txt_path, "w", encoding="utf-8") as f:
        f.write("\n\n".join(scenes) + "\n")

    if not os.path.exists(mp3):
        print(f"[{pid}] TTS...", flush=True)
        r = subprocess.run([PY, TTS_SCRIPT, "--text-file", txt_path, "--out", mp3],
                           capture_output=True, text=True)
        if not os.path.exists(mp3):
            print(f"[{pid}] TTS 失败:\n{r.stdout[-800:]}\n{r.stderr[-800:]}", flush=True)
            raise SystemExit(1)
    meta = json.load(open(os.path.join(d, "narration.json"), encoding="utf-8"))
    duration = float(meta.get("duration", meta.get("duration_s")))
    print(f"[{pid}] TTS ok: {duration:.2f}s", flush=True)

    # 转写（模型只加载一次的场景放在外层）
    words = transcribe(mp3)
    json.dump(words, open(os.path.join(d, "transcript.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=2)
    print(f"[{pid}] 转写 ok: {len(words)} 词", flush=True)

    # DP 对齐
    units = []
    for w in words:
        txt = (w["text"] or "").strip()
        if not txt:
            continue
        cjk = only_cjk(txt)
        for p in (py(cjk) if cjk else py(txt)):
            units.append((p, float(w["start"]), float(w["end"])))
    tgt_pys = [u[0] for u in units]

    # 场景边界（段首字符偏移）
    scene_offsets, pos = [], 0
    for sc in scenes:
        scene_offsets.append(pos)
        pos += len(only_cjk(sc))
    all_text = "".join(only_cjk(sc) for sc in scenes)
    src_pys = py(all_text)
    align = dp_align(src_pys, tgt_pys)

    scene_starts = []
    for off in scene_offsets:
        t = char_time(align, units, off, "start") if off > 0 else 0.0
        scene_starts.append(round(max(0.0, t - 0.05), 3))

    # 字幕
    caps, pos = [], 0
    for sc in scenes:
        for chunk in split_captions(sc):
            cjk = only_cjk(chunk)
            s0, e0 = pos, pos + len(cjk)
            pos = e0
            ts = [char_time(align, units, k, "start") for k in range(s0, e0)]
            te = [char_time(align, units, k, "end") for k in range(s0, e0)]
            caps.append({
                "text": re.sub(r"[，。；：？！、,\"\"''——·]", "", chunk).replace("——", ""),
                "start": round(min(ts), 3),
                "end": round(max(te), 3),
            })
    manifest = {
        "part": pid, "duration": duration,
        "scenes": [{"text": sc, "start": scene_starts[i]} for i, sc in enumerate(scenes)],
        "captions": caps,
    }
    json.dump(manifest, open(manifest_path, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"[{pid}] manifest ok: {len(scenes)} 幕 / {len(caps)} 条字幕", flush=True)


_MODEL = None
def transcribe(mp3):
    global _MODEL
    if _MODEL is None:
        from faster_whisper import WhisperModel
        _MODEL = WhisperModel("small", device="cpu", compute_type="int8",
                              cpu_threads=min(8, os.cpu_count() or 4))
    segments, info = _MODEL.transcribe(str(mp3), language="zh", beam_size=5,
                                       word_timestamps=True, vad_filter=False,
                                       condition_on_previous_text=False)
    words = []
    for seg in segments:
        for w in (seg.words or []):
            text = (w.word or "").strip()
            if text:
                words.append({"text": text, "start": round(float(w.start), 3),
                              "end": round(float(w.end), 3)})
    return words


